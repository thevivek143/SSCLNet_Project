# PDF GENERATION
# ==========================================

def generate_report(image, heatmap, diagnosis_text, probability_text):
    """
    Generates a PDF report using ReportLab.
    """
    if image is None:
        return None

    # Create reports directory
    os.makedirs("reports", exist_ok=True)
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"reports/SSCLNet_Report_{timestamp}.pdf"
    
    # Define temp image paths
    temp_img_path = f"reports/temp_img_{timestamp}.jpg"
    temp_cam_path = f"reports/temp_cam_{timestamp}.jpg"
    
    try:
        # Save temp images for insertion
        if isinstance(image, np.ndarray):
            Image.fromarray(image).save(temp_img_path)
        else:
            image.save(temp_img_path) # Assumed PIL
            
        # Heatmap Image
        if isinstance(heatmap, np.ndarray):
            Image.fromarray(heatmap).save(temp_cam_path)
        else:
             if heatmap is not None:
                heatmap.save(temp_cam_path)
        
        # Create PDF
        c = canvas.Canvas(filename, pagesize=letter)
        width, height = letter
        
        # Header
        c.setFillColor(HexColor("#0f766e")) # Teal
        c.setFont("Helvetica-Bold", 24)
        c.drawString(50, height - 50, "SSCLNet Diagnostic Report")
        
        c.setFillColor(HexColor("#334155")) # Slate
        c.setFont("Helvetica", 12)
        c.drawString(50, height - 75, f"Date: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}")
        c.drawString(50, height - 90, f"Report ID: {timestamp}")
        
        c.line(50, height - 100, width - 50, height - 100)
        
        # Diagnosis Section
        c.setFont("Helvetica-Bold", 16)
        c.drawString(50, height - 140, "Diagnostic Assessment")
        
        c.setFont("Helvetica", 14)
        c.setFillColor(HexColor("#000000"))
        c.drawString(50, height - 170, f"Predicted Condition: {diagnosis_text}")
        c.drawString(50, height - 190, f"Model Confidence: {probability_text}")

        # Images Section
        c.setFont("Helvetica-Bold", 16)
        c.drawString(50, height - 240, "Visual Analysis")
        
        # Draw images (Resize to fit)
        c.drawString(50, height - 265, "Original Scan")
        c.drawImage(temp_img_path, 50, height - 500, width=220, height=220, preserveAspectRatio=True)
        
        if os.path.exists(temp_cam_path):
            c.drawString(300, height - 265, "Attention Map (Grad-CAM)")
            c.drawImage(temp_cam_path, 300, height - 500, width=220, height=220, preserveAspectRatio=True)
        
        # Footer
        c.setFont("Helvetica-Oblique", 10)
        c.setFillColor(HexColor("#64748b"))
        c.drawString(50, 50, "Generated by SSCLNet.")
        
        c.save()
        
        # Cleanup temp files
        if os.path.exists(temp_img_path): os.remove(temp_img_path)
        if os.path.exists(temp_cam_path): os.remove(temp_cam_path)
            
        return filename

    except Exception as e:
        print(f"PDF Error: {e}")
        return None

