def predict_advanced(image, task):
    if image is None:
        return None, None, gr.HTML(""), "", ""

    try:
        pil_image = Image.fromarray(image).convert("RGB")
        img_tensor = transform(pil_image).unsqueeze(0).to(DEVICE)

        with torch.enable_grad():
            if task == "Brain MRI":
                if brain_model is None: raise gr.Error("Brain Model not loaded.")
                model = brain_model
                cam_tool = brain_cam_tool
                classes = BRAIN_CLASSES
            elif task == "Knee Osteoarthritis":
                if knee_model is None: raise gr.Error("Knee Model not loaded.")
                model = knee_model
                cam_tool = knee_cam_tool
                classes = KNEE_CLASSES
            else:
                raise gr.Error("Invalid Task")

            outputs = model(img_tensor)
            probs = F.softmax(outputs, dim=1)[0].detach().numpy()
            
            top_class_idx = np.argmax(probs)
            top_class_label = classes[top_class_idx]
            confidence_val = probs[top_class_idx]*100
            
            heatmap = cam_tool(img_tensor, class_idx=top_class_idx)
            vis_img = overlay_heatmap(heatmap, pil_image)
            
            label_dict = {classes[i]: float(probs[i]) for i in range(len(classes))}
            
            html_output = f"""
            <div style='background-color: #f0fdf4; padding: 15px; border-radius: 10px; border: 1px solid #bbf7d0;'>
                <h3 style='color: #166534; margin: 0;'>Diagnosis: {top_class_label}</h3>
                <p style='color: #15803d; font-size: 14px; margin-top: 5px;'>Confidence: <strong>{confidence_val:.1f}%</strong></p>
            </div>
            """
            
            # Return raw strings for the PDF generator state as well
            return label_dict, vis_img, html_output, top_class_label, f"{confidence_val:.1f}%"

    except Exception as e:
        raise gr.Error(f"Analysis failed: {str(e)}")

def generate_pdf_wrapper(image, heatmap, diagnosis, confidence):
    if not diagnosis or not confidence:
        raise gr.Error("Please run analysis first.")
    
    path = generate_report(image, heatmap, diagnosis, confidence)
    return path

