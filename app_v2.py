def create_app_v2():
    with gr.Blocks(title="SSCLNet Analysis") as app:
        
        # Hidden states to store strings for PDF report
        diagnosis_state = gr.State()
        confidence_state = gr.State()

        # Header Area
        with gr.Row():
            with gr.Column(scale=1): # Use full width column effectively for centering
                gr.HTML("""
                <h1 style="text-align: center; margin-bottom: 0;">🏥 <strong>SSCLNet Medical Image Analysis</strong></h1>
                """)
        
        gr.Markdown("---")
        
        # Main Layout: Sidebar + Content
        with gr.Row():
            
            # LEFT SIDEBAR: Controls
            with gr.Column(scale=1, variant="panel"):
                
                task_selector = gr.Radio(
                    ["Brain MRI", "Knee Osteoarthritis"],
                    label="Clinical Task",
                    value="Brain MRI",
                    info="Select valid model pipeline"
                )
                
                input_image = gr.Image(
                    type="numpy", 
                    label="Patient Scan",
                    sources=["upload"],
                    height=300
                )
                
                run_btn = gr.Button("🔍 Run Analysis", variant="primary", size="lg")
                clear_btn = gr.Button("🗑️ Reset Workspace", variant="secondary")
                
                gr.Markdown("---")
                gr.Markdown("### 📄 Reporting")
                report_btn = gr.Button("Download Medical Report")
                report_file = gr.File(label="PDF Report")

            
            # RIGHT CONTENT: Results
            with gr.Column(scale=2):
                gr.Markdown("### 📊 Diagnostic Results")
                
                # Tabbed Output
                with gr.Tabs():
                    with gr.TabItem("📈 Prediction"):
                        result_html = gr.HTML(label="Top Diagnosis")
                        conf_labels = gr.Label(num_top_classes=4, label="Class Probabilities")
                    
                    with gr.TabItem("👁️ Visual Explanation (Grad-CAM)"):
                        cam_output = gr.Image(label="Attention Heatmap", interactive=False)
                        gr.Markdown("*Warmer colors (Red/Yellow) indicate regions the AI focused on.*")

        
        # Functionality
        run_btn.click(
            fn=predict_advanced,
            inputs=[input_image, task_selector],
            outputs=[conf_labels, cam_output, result_html, diagnosis_state, confidence_state]
        )
        
        report_btn.click(
            fn=generate_pdf_wrapper,
            inputs=[input_image, cam_output, diagnosis_state, confidence_state],
            outputs=[report_file]
        )
        
        clear_btn.click(
            lambda: (None, None, None, None, None, None, None),
            outputs=[input_image, conf_labels, cam_output, result_html, report_file, diagnosis_state, confidence_state]
        )

    return app

